# ================================== 通用工具函数 ==================================
def parse_line_content(line):
    """解析单行日志内容（兼容弹幕/礼物格式）"""
    if not line:
        return None
    raw_content = line.strip()
    if ":" in raw_content:
        content = raw_content.split(":", 1)[1].strip()
    else:
        content = raw_content
    return content if len(content) >= 2 else None

# ================================== 字节跳动 TTS 核心函数 ==================================
async def tts_http_generate(text, temp_audio_path):
    """通过HTTP接口调用字节跳动TTS生成音频文件"""
    request_data = {
        "app": {
            "appid": TTS_APPID,
            "token": TTS_TOKEN,
            "cluster": TTS_CLUSTER
        },
        "user": {
            "uid": "fairy_live_001"
        },
        "audio": {
            "voice_type": TTS_VOICE_TYPE,
            "encoding": "mp3",
            "speed_ratio": 1.0,
            "loudness_ratio": 1.0,
            "pitch_ratio": 1.0
        },
        "request": {
            "reqid": str(uuid.uuid4()),
            "text": text,
            "operation": "query"
        }
    }

    headers = {
        "Content-Type": "application/json",
        "Authorization": f"Bearer;{TTS_TOKEN}",
        "Resource-Id": TTS_RESOURCE_ID
    }

    try:
        async with httpx.AsyncClient(timeout=30.0) as http_client:
            response = await http_client.post(
                TTS_HTTP_URL,
                json=request_data,
                headers=headers
            )
        response.raise_for_status()
        result = response.json()

        if result.get("code") == 3000 and result.get("data"):
            audio_bytes = base64.b64decode(result["data"])
            with open(temp_audio_path, "wb") as f:
                f.write(audio_bytes)
            if os.path.getsize(temp_audio_path) > 0:
                return True
            else:
                print(f"❌ TTS生成空文件：{temp_audio_path}")
                return False
        else:
            print(f"❌ TTS合成失败：{result.get('message', '未知错误')}")
            return False
    except Exception as e:
        print(f"❌ TTS HTTP调用失败：{str(e)[:200]}")
        if os.path.exists(temp_audio_path):
            os.remove(temp_audio_path)
        return False

