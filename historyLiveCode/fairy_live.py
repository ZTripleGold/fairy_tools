def get_fairy_reply(message_text, msg_type="弹幕"):
    """获取Fairy回复（使用SiliconFlow基础模型 + 完整人设）"""
    try:
        # 构造用户消息（带类型前缀）
        user_prompt = f"【{msg_type}消息】{message_text}，回复要求：口语化、简洁，字数控制在{MAX_REPLY_LENGTH}字内"

        # 流式调用
        stream = client.chat.completions.create(
            model=SILICONFLOW_MODEL,
            messages=[
                {"role": "system", "content": FAIRY_SYSTEM_PROMPT},
                {"role": "user", "content": user_prompt}
            ],
            stream=True,
            max_tokens=MAX_REPLY_LENGTH * 2,
            temperature=0.8
        )

        reply_content = ""
        for chunk in stream:
            if chunk.choices and chunk.choices[0].delta.content:
                reply_content += chunk.choices[0].delta.content

        if len(reply_content) > MAX_REPLY_LENGTH:
            reply_content = reply_content[:MAX_REPLY_LENGTH]
        return reply_content.strip()

    except Exception as e:
        print(f"❌ SiliconFlow调用异常：{str(e)}")
        import traceback
        traceback.print_exc()
        return None

