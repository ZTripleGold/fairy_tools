async def tts_http_generate(text, temp_audio_path, role, max_retries=3, retry_delay_base=1.0):
    tts_config = FAIRY_TTS_CONFIG if role == "fairy" else YOUKAI_TTS_CONFIG
    tts_config["text"] = text
    headers = {
        "Content-Type": "application/json; charset=utf-8"
    }
    last_error = None

    for attempt in range(1, max_retries + 1):
        try:
            print(f"🔄 [{role}] TTS生成第{attempt}/{max_retries}次尝试...")
            async with httpx.AsyncClient(timeout=60.0) as http_client:
                response = await http_client.post(
                    TTS_INFER_URL,
                    json=tts_config,
                    headers=headers,
                    follow_redirects=True
                )
            response.raise_for_status()

            try:
                result = response.json()
                audio_url = result.get("audio_url") or result.get("url") or result.get("dl_url") or result.get("output_url")
                if not audio_url:
                    audio_url = response.text.strip()
            except json.JSONDecodeError:
                audio_url = response.text.strip()

            if audio_url:
                audio_url = audio_url.replace("/infer_classic/outputs/", "/outputs/")
                if "infer_classic" in audio_url and "117.50.34.106:8000" in audio_url:
                    audio_url = audio_url.replace("http://117.50.34.106:8000/infer_classic/outputs/", 
                                                 "http://117.50.34.106:8000/outputs/")

            if not audio_url or not audio_url.startswith("http"):
                raise ValueError(f"接口返回无效链接：{audio_url}")
            print(f"✅ [{role}] 获取音频下载链接：{audio_url}")

            async with httpx.AsyncClient(timeout=60.0) as http_client:
                audio_response = await http_client.get(audio_url, follow_redirects=True)
            audio_response.raise_for_status()
            audio_data = audio_response.content

            if not audio_data.startswith(b'RIFF'):
                raise ValueError(f"下载的不是标准WAV文件！前10字节：{audio_data[:10]}")

            with open(temp_audio_path, "wb") as f:
                f.write(audio_data)

            if os.path.getsize(temp_audio_path) > 100:
                print(f"✅ [{role}] TTS生成成功（第{attempt}次）")
                return True
            else:
                raise ValueError(f"下载的音频文件为空/无效：{temp_audio_path}")

        except Exception as e:
            last_error = e
            error_msg = str(e)[:150]
            print(f"❌ [{role}] TTS第{attempt}次尝试失败：{error_msg}")

            if os.path.exists(temp_audio_path):
                try:
                    os.remove(temp_audio_path)
                except:
                    pass

            if attempt < max_retries:
                retry_delay = retry_delay_base * (2 ** (attempt - 1))
                print(f"⏱️ [{role}] {retry_delay}秒后重试...")
                await asyncio.sleep(retry_delay)
            else:
                print(f"❌ [{role}] TTS生成失败（已达最大重试次数{max_retries}次）")

    return False

