def check_directory(dir_path: str, label: str, expected_texts: list = None):
    """检查单个目录"""
    print(f"\n{'='*70}")
    print(f"📁 检查目录: {label}")
    print(f"   路径: {dir_path}")
    print(f"{'='*70}")

    if not os.path.exists(dir_path):
        print(f"   ❌ 目录不存在!")
        return {"missing_dir": True, "missing": [], "extra": [], "matched": []}

    file_map = get_all_texts_from_dir(dir_path)
    print(f"   目录中音频文件数: {len(file_map)}")

    if expected_texts is None:
        # 仅检查存在性
        print(f"   ✅ 目录存在，共 {len(file_map)} 个音频文件（内容随机，不核对）")
        return {"missing_dir": False, "missing": [], "extra": list(file_map.values()), "matched": []}

    matched = []
    missing = []

    print(f"\n   期望语录数: {len(expected_texts)}")
    print(f"   {'─'*60}")

    for i, text in enumerate(expected_texts, 1):
        match_file, score = find_best_match(text, file_map)

        if score == 1.0:
            matched.append((text, match_file))
            print(f"   ✅ [{i}] 匹配: {match_file}")
        elif score > 0.5:
            # 部分匹配，可能是标点差异
            matched.append((text, match_file))
            print(f"   ⚠️  [{i}] 部分匹配 (相似度{score:.0%}): {match_file}")
            print(f"      原文: {text[:50]}...")
        else:
            missing.append(text)
            print(f"   ❌ [{i}] 缺失")
            print(f"      原文: {text[:60]}...")

    # 找多余文件
    used_files = set(f for _, f in matched)
    extra = [f for f in file_map.values() if f not in used_files]

    print(f"\n   {'─'*60}")
    print(f"   结果: ✅匹配 {len(matched)} | ❌缺失 {len(missing)} | ⚠️多余 {len(extra)}")

    if extra:
        print(f"\n   ⚠️ 多余文件 (目录中有但语录未定义):")
        for f in extra:
            print(f"      • {f}")

    return {
        "missing_dir": False,
        "missing": missing,
        "extra": extra,
        "matched": matched
    }


