# ================================== 核心工具函数 ==================================

def normalize_text(text: str) -> str:
    """
    标准化文本：只保留汉字、字母、数字，用于内容比对
    忽略所有标点符号、空格、特殊字符
    """
    # 保留：汉字 一-鿿、字母 a-zA-Z、数字 0-9
    return re.sub(r'[^一-龥a-zA-Z0-9]', '', text)


def get_all_texts_from_dir(dir_path: str) -> dict:
    """
    扫描目录中的所有mp3文件，返回 {标准化文本: 原始文件名}
    """
    result = {}
    if not os.path.exists(dir_path):
        return result

    for filename in os.listdir(dir_path):
        if filename.lower().endswith('.mp3'):
            # 去掉 .mp3 后缀
            name_without_ext = filename[:-4]
            normalized = normalize_text(name_without_ext)
            if normalized:
                result[normalized] = filename
    return result


def find_best_match(text: str, file_map: dict) -> tuple:
    """
    在文件映射中找到最佳匹配
    返回: (匹配的文件名, 相似度)
    """
    normalized = normalize_text(text)
    if not normalized:
        return None, 0

    # 精确匹配
    if normalized in file_map:
        return file_map[normalized], 1.0

    # 模糊匹配：找最长公共子串比例最高的
    best_match = None
    best_score = 0

    for norm_file, orig_file in file_map.items():
        # 简单相似度：较短的包含在较长的里面
        if normalized in norm_file or norm_file in normalized:
            score = len(normalized) / max(len(normalized), len(norm_file))
            if score > best_score:
                best_score = score
                best_match = orig_file

    return best_match, best_score


